#!/usr/bin/env python3
"""Route a change to the files that govern it. Identical in every fleet repo.

Every AI agent (Claude, Codex/ChatGPT, Gemini, Grok, Copilot), in the browser
or in an app, uses the same workflow:

    python3 tools/agent_route.py route <changed or planned files...>

prints, for each topic the files match, the documents to read first. Topics
come from two files:

  docs/agents/fleet-topics.json  shared by every fleet repo, byte-identical
  docs/agents/topics.json        this repo's own topics

A "read" entry is a path, or "path § Heading" to point at one section; the
heading must exist in that file.

    python3 tools/agent_route.py check            # this repo
    python3 tools/agent_route.py check --fleet DIR...   # and compare repos
    python3 tools/agent_route.py generate         # rewrite AGENTS.md's table and area AGENTS.md files
    python3 tools/agent_route.py owner <md...>    # which topic owns each document

A topic may also carry `parent` (the layer it sits on: route prints parents
first, common layers before specific ones), `owns` (patterns for the Markdown
files it is responsible for; every tracked .md must be owned by some topic, so
a new document cannot sit where no agent is sent) and `area` (a folder that
gets its own generated AGENTS.md, so an agent working inside it reads the
layer for that area).

check fails (exit 1) on: a read file or heading that does not exist, a topic
whose paths match no tracked file, a duplicate topic id, a parent that is not a
topic, an owns pattern that matches no document, a Markdown file no topic owns,
a stale generated table in AGENTS.md or area AGENTS.md, or (with --fleet) a fleet-topics.json that differs between
repos. Exit 2 means it could not look (no git, unreadable file), which is
never a pass.
"""
import re
import json
import os
import pathlib
import subprocess  # nosec B404 - only runs `git ls-files` with fixed arguments
import sys

FLEET = "docs/agents/fleet-topics.json"
LOCAL = "docs/agents/topics.json"
START = "<!-- agent-routes:start (generated by tools/agent_route.py; do not edit) -->"
END = "<!-- agent-routes:end -->"


class CouldNotLook(Exception):
    pass


def load(root):
    topics = []
    for rel, scope in ((FLEET, "fleet"), (LOCAL, "local")):
        p = root / rel
        if not p.is_file():
            raise CouldNotLook(f"{rel} missing")
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:  # UnicodeDecodeError is a ValueError
            raise CouldNotLook(f"{rel}: {e}")
        try:
            topics += [dict(t, scope=scope) for t in data["topics"]]
        except (KeyError, TypeError) as e:
            raise CouldNotLook(f"{rel}: malformed ({e!r})")
    return topics


# A caller's GIT_DIR / GIT_INDEX_FILE (a hook, a wrapper) must not redirect git to another repository.
_GIT_ENV = {k: v for k, v in os.environ.items()
            if k not in {"GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_OBJECT_DIRECTORY", "GIT_COMMON_DIR"}}


def read(path):
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise CouldNotLook(f"{path.name}: {e}")


def tracked(root):
    try:
        # Fixed argv, no shell; root comes from this file's own location or --fleet, never from a network input.
        out = subprocess.run(["git", "-C", str(root), "ls-files"], capture_output=True,  # nosec B603 B607 - fixed argv, git from PATH  # reeflint: no-winproc fleet-wide tool, the same file in every repo; run from CI or a dev shell, never the box UI
                             text=True, check=True, env=_GIT_ENV).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        raise CouldNotLook(f"git ls-files: {e}")
    return [line for line in out.splitlines() if line]


_GLOB_CACHE = {}


def _glob_re(pattern):
    """Glob to regex: `**` crosses folders, `*` and `?` stay inside one, `dir/` means everything under it."""
    if pattern not in _GLOB_CACHE:
        pat = pattern + "**" if pattern.endswith("/") else pattern
        out, i = [], 0
        while i < len(pat):
            if pat.startswith("**/", i):
                out.append("(?:.*/)?")
                i += 3
            elif pat.startswith("**", i):
                out.append(".*")
                i += 2
            elif pat[i] == "*":
                out.append("[^/]*")
                i += 1
            elif pat[i] == "?":
                out.append("[^/]")
                i += 1
            else:
                out.append(re.escape(pat[i]))
                i += 1
        _GLOB_CACHE[pattern] = re.compile("".join(out) + r"\Z")
    return _GLOB_CACHE[pattern]


def matches(pattern, path):
    return _glob_re(pattern).match(path) is not None


def split_ref(ref):
    path, _, heading = ref.partition(" § ")
    return path.strip(), heading.strip()


def has_heading(text, heading):
    for line in text.splitlines():
        s = line.lstrip()
        if s.startswith("#") and s.lstrip("#").strip().startswith(heading):
            return True
    return False


def chain(topics, t):
    """The topic and its parents, outermost (most common) first."""
    by_id = {x["id"]: x for x in topics}
    out, seen = [], set()
    while t is not None and t["id"] not in seen:
        seen.add(t["id"])
        out.insert(0, t)
        t = by_id.get(t.get("parent"))
    return out


def route(topics, files):
    """Every topic the files match, each preceded by its parents (common layers first), no repeats."""
    hit, seen = [], set()
    for t in topics:
        # A topic that owns a document is also a topic for changing it.
        if any(matches(p, f) for f in files for p in t["paths"] + t.get("owns", [])):
            for c in chain(topics, t):
                if c["id"] not in seen:
                    seen.add(c["id"])
                    hit.append(c)
    return hit


def owner(topics, md):
    """The most specific topic that owns a Markdown file (longest matching `owns` pattern), or None."""
    best, best_len = None, -1
    for t in topics:
        for g in t.get("owns", []):
            if matches(g, md) and len(g) > best_len:
                best, best_len = t, len(g)
    return best


def area_stub(topics, t):
    """The generated AGENTS.md for an area folder, so an agent working inside it reads its layer."""
    rows = []
    for c in chain(topics, t):
        rows.append(f"- **{c['title']}** (`{c['id']}`)")
        rows += [f"  - read: `{r}`" for r in c["read"]]
    return "\n".join([
        f"# {t['title']}: read this before any work here",
        "",
        "Generated by `tools/agent_route.py generate` from `docs/agents/topics.json`; do not edit.",
        "The root [`AGENTS.md`](" + "../" * t["area"].strip("/").count("/") + "../AGENTS.md) applies here too.",
        "For the files a specific change needs, run `python3 tools/agent_route.py route <files>` from the repository root.",
        "",
        "Read in this order (the common layers first):",
        "",
        *rows,
        "",
    ])


def table(topics):
    rows = ["| topic | applies to | read first |", "|---|---|---|"]
    for t in topics:
        paths = ", ".join(f"`{p}`" for p in t["paths"])
        reads = "<br>".join(f"`{r}`" for r in t["read"])
        under = f", under `{t['parent']}`" if t.get("parent") else ""
        rows.append(f"| **{t['title']}** (`{t['id']}`, {t['scope']}{under}) | {paths} | {reads} |")
    return "\n".join([START, "", *rows, "", END])


def check(root):
    problems = []
    topics = load(root)
    files = tracked(root)
    seen = set()
    for t in topics:
        if t["id"] in seen:
            problems.append(f"duplicate topic id {t['id']}")
        seen.add(t["id"])
        if not any(matches(p, f) for f in files for p in t["paths"]):
            problems.append(f"{t['id']}: paths {t['paths']} match no tracked file")
        if t.get("parent") and t["parent"] not in {x["id"] for x in topics}:
            problems.append(f"{t['id']}: parent {t['parent']} is not a topic")
        mds = [f for f in files if f.endswith(".md")]
        for g in t.get("owns", []):
            if not any(matches(g, f) for f in mds):
                problems.append(f"{t['id']}: owns {g} but no Markdown file matches it")
        if t.get("area"):
            stub = root / t["area"].strip("/") / "AGENTS.md"
            if not stub.is_file() or read(stub) != area_stub(topics, t):
                problems.append(f"{stub.relative_to(root)} is missing or stale (run generate)")
        for ref in t["read"]:
            path, heading = split_ref(ref)
            p = root / path
            if not (p.is_file() or (path.endswith("/") and p.is_dir())):
                problems.append(f"{t['id']}: read file {path} does not exist")
            elif heading and not has_heading(read(p), heading):
                problems.append(f"{t['id']}: {path} has no heading starting '{heading}'")
    # Every Markdown file belongs to a topic, so a new document cannot sit where no agent is sent.
    for md in (f for f in files if f.endswith(".md")):
        own = owner(topics, md)
        if own is None:
            problems.append(f"{md}: no topic owns this document (add it to a topic's owns)")
        elif own["id"] not in {t["id"] for t in route(topics, [md])}:
            problems.append(f"{md}: owned by {own['id']} but its paths do not route this document there")
    agents = read(root / "AGENTS.md")
    if START not in agents or END not in agents:
        problems.append("AGENTS.md has no generated agent-routes table (run generate)")
    elif agents[agents.index(START):agents.index(END) + len(END)] != table(topics):
        problems.append("AGENTS.md agent-routes table is stale (run generate)")
    return problems


def generate(root):
    topics = load(root)
    p = root / "AGENTS.md"
    text = p.read_text(encoding="utf-8")
    block = table(topics)
    if START in text and END in text:
        text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        marker = "## Every AI agent reads this file first"
        i = text.find(marker)
        head = "## Which files govern my change?\n\nRun `python3 tools/agent_route.py route <files>`; it prints the same rows.\n\n"
        if i < 0:
            text = text.rstrip() + "\n\n" + head + block + "\n"
        else:
            j = text.find("\n## ", i + len(marker))
            j = len(text) if j < 0 else j + 1
            text = text[:j] + head + block + "\n\n" + text[j:]
    p.write_text(text, encoding="utf-8")
    for t in topics:
        if t.get("area"):
            (root / t["area"].strip("/") / "AGENTS.md").write_text(area_stub(topics, t), encoding="utf-8")


def owners(root, files):
    topics = load(root)
    for f in files:
        t = owner(topics, f)
        print(f"{f}: {t['id'] if t else 'NO OWNER'}")


def main(argv):
    root = pathlib.Path(__file__).resolve().parent.parent
    cmd = argv[0] if argv else "check"
    try:
        if cmd == "route":
            # Paths are repository-relative with "/"; "./x" and "x\\y" name the same file.
            files = [a.replace("\\", "/").removeprefix("./") for a in argv[1:]]
            for t in route(load(root), files):
                print(f"[{t['scope']}] {t['title']}")
                for r in t["read"]:
                    print(f"    read: {r}")
            return 0
        if cmd == "owner":
            owners(root, argv[1:])
            return 0
        if cmd == "generate":
            generate(root)
            print("AGENTS.md agent-routes table written")
            return 0
        if cmd != "check":
            print(__doc__)
            return 2
        roots = [root]
        if "--fleet" in argv:
            roots += [pathlib.Path(a).resolve() for a in argv[argv.index("--fleet") + 1:]]
        rc, first = 0, None
        for r in roots:
            try:
                problems = check(r)
                fleet = (r / FLEET).read_bytes()
            except CouldNotLook as e:
                print(f"UNKNOWN {r.name}: {e}")
                rc = max(rc, 2)
                continue
            if first is None:
                first = fleet
            elif fleet != first:
                problems.append(f"{FLEET} differs from {roots[0].name}")
            for pr in problems:
                print(f"DRIFT {r.name}: {pr}")
            if not problems:
                print(f"ok {r.name}")
            rc = max(rc, 1 if problems else 0)
        return rc
    except CouldNotLook as e:
        print(f"UNKNOWN: {e}")
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
